"""Genetic Opt submodule to load the runs saved by `fit`."""

from collections.abc import Callable, Iterator
from contextlib import contextmanager
from itertools import pairwise
from math import inf, isinf
from operator import itemgetter
from os.path import getsize
from pathlib import Path
from typing import Any

from genetic_opt.chromosome import Chromosome
from genetic_opt.exceptions import ValidationException
from genetic_opt.functions import identity_func
from genetic_opt.metrics import Metric
from genetic_opt.runs.files import (
    get_files_inside_folder,
    load_bson,
    load_json,
)
from genetic_opt.runs.fit_result import (
    FitResult,
    FitResultFile,
    FitSummary,
)
from genetic_opt.score import Score


def load_fit_result(
    folder_path: str,
    decode_func: Callable[[Chromosome], Any],
    load_decoded_chromosome_func: Callable[[Any], Any] | None = None,
    load_gene_func: Callable[[Any], Any] | None = None,
    remove_duplicates: bool = False,
    max_file_bytes: int | None = None,
) -> FitResult:
    """
    Load the content generated by `GeneticAlgorithm.fit` method.
    :param folder_path: Path of the `fit_data` folder, which contains the
        saved response of the function `GeneticAlgorithm.fit`.
    :param decode_func: the `decode_func` of the algorithm that made the
        run. It decodes the last population into `last_population`, which
        the files do not hold since 2.0.0.
    :param load_decoded_chromosome_func: Function to load serialized
        Chromosomes. It is the identity function by default.
    :param load_gene_func: Function to load serialized Genes. It is the
        identity function by default.
    :param remove_duplicates: whether to remove duplicated chromosomes in
        each population. Default to False.
    :param max_file_bytes: size over which a file is refused without
        being read. No limit by default, so a file of any size is read
        whole into memory.
    :raises ValidationException: the folder is missing or empty, a file
        is larger than `max_file_bytes`, its content is not the one of
        a fit result file, or two files hold the same generation.
    :return: a `FitResult`, with the keys `GeneticAlgorithm.fit` returns.
        `fit_metrics`, `fit_parameters` and `config` are as the files
        hold them.
    """
    files = get_files_inside_folder(folder_path, return_complete_path=True)
    load_decoded_chromosome_func = (
        _let_errors_out(load_decoded_chromosome_func) or identity_func
    )
    load_gene_func = _let_errors_out(load_gene_func)
    # Every file gives its population and the metrics of its own
    # generation: the last of its `metrics`, which are all the
    # generations so far in a file saved before 0.7.0. The rest is read
    # from the file of the last generation only, kept in `last_raw`.
    generations: list[tuple[int, str, list, Metric]] = []
    last_idx, last_raw, last_population = None, None, []
    for file in files:
        with _refuse_malformed(file):
            raw = _read_fit_result_file(file, max_file_bytes)
            population_idx = raw["population_idx"]
            population = _load_population(raw["population"], load_gene_func)
            (metric,) = _load_metrics(
                raw["metrics"][-1:],
                load_decoded_chromosome_func,
                load_gene_func,
            )
            if last_idx is None or population_idx > last_idx:
                last_idx, last_raw = population_idx, raw
                last_population = population
            if remove_duplicates:
                population = _remove_duplicates(population)
            generations.append((population_idx, file, population, metric))
    if not generations:
        raise ValidationException(f"`{folder_path}` has no fit result file")
    generations.sort(key=itemgetter(0))
    for (idx, file, *_), (next_idx, next_file, *_) in pairwise(generations):
        if idx == next_idx:
            raise ValidationException(
                f"`{file}` and `{next_file}` both hold generation {idx}"
            )
    with _refuse_malformed(generations[-1][1]):
        response = _load_fit_summary(
            last_raw, load_decoded_chromosome_func, load_gene_func
        )
    # Decoded as `fit` decodes it: with its duplicates. A file saved
    # before 2.0.0 also holds it decoded, as `last_population`, which
    # is not read.
    response["last_population"] = [
        (decode_func(chromosome), score)
        for score, chromosome in last_population
    ]
    response["metrics"] = [metric for *_, metric in generations]
    response["history"] = [population for _, _, population, _ in generations]
    return response


def load_fit_result_file(
    file_path: str,
    load_decoded_chromosome_func: Callable[[Any], Any] | None = None,
    load_gene_func: Callable[[Any], Any] | None = None,
    remove_duplicates: bool = False,
    max_file_bytes: int | None = None,
) -> FitResultFile:
    """
    Load the content of a single file generated by the `GeneticAlgorithm.fit`
    method.
    :param file_path: Path of a BSON/JSON file.
    :param load_decoded_chromosome_func: Function to load serialized
        Chromosomes. It is the identity function by default.
    :param load_gene_func: Function to load serialized Genes. It is the
        identity function by default.
    :param remove_duplicates: whether to remove duplicated chromosomes in
        each population. Default to False.
    :param max_file_bytes: size over which the file is refused without
        being read. No limit by default, so a file of any size is read
        whole into memory.
    :raises ValidationException: the file is larger than
        `max_file_bytes`, or its content is not the one of a fit result
        file.
    :return: a `FitResultFile`.
    """
    load_decoded_chromosome_func = (
        _let_errors_out(load_decoded_chromosome_func) or identity_func
    )
    load_gene_func = _let_errors_out(load_gene_func)
    with _refuse_malformed(file_path):
        raw = _read_fit_result_file(file_path, max_file_bytes)
        response = _load_fit_summary(
            raw, load_decoded_chromosome_func, load_gene_func
        )
        response["metrics"] = _load_metrics(
            raw["metrics"], load_decoded_chromosome_func, load_gene_func
        )
        response["population"] = _load_population(
            raw["population"], load_gene_func
        )
        if remove_duplicates:
            response["population"] = _remove_duplicates(
                response["population"]
            )
        response["population_idx"] = raw["population_idx"]
    return response


class _CallerError(Exception):
    """An error of a function the caller passed, carried as its cause."""


def _let_errors_out(
    func: Callable[[Any], Any] | None,
) -> Callable[[Any], Any] | None:
    """
    Wrap a function the caller passed, so that `_refuse_malformed` lets
    its errors out as they are instead of refusing the file.

    :param func: the function, or `None`.
    :return: the wrapped function, or `None` when `func` is `None`.
    """
    if func is None:
        return None

    def wrapped(value: Any) -> Any:
        try:
            return func(value)
        except Exception as error:
            raise _CallerError from error

    return wrapped


@contextmanager
def _refuse_malformed(file_path: str) -> Iterator[None]:
    """Turn the raw errors of a malformed file into a refusal of it."""
    from bson.errors import BSONError

    caller_error = None
    try:
        yield
    except _CallerError as error:
        caller_error = error.__cause__
    except (
        AttributeError,
        BSONError,
        IndexError,
        KeyError,
        TypeError,
        ValueError,
    ) as error:
        raise ValidationException(
            f"`{file_path}` is not a fit result file: {error!r}"
        ) from error
    # Raised outside the `except`, so that the error keeps its own chain.
    if caller_error is not None:
        raise caller_error


def _read_fit_result_file(file_path: str, max_file_bytes: int | None) -> dict:
    """Parse a fit result file, refusing one over `max_file_bytes`."""
    if max_file_bytes is not None and getsize(file_path) > max_file_bytes:
        raise ValidationException(
            f"`{file_path}` has {getsize(file_path)} bytes, more than "
            f"{max_file_bytes = }"
        )
    if Path(file_path).suffix == ".bson":
        return load_bson(file_path)
    return load_json(file_path)


def _load_population(
    population: list, load_gene_func: Callable[[Any], Any] | None
) -> list[tuple[Score, Chromosome]]:
    """Load the population of a parsed fit result file."""
    return [
        (Score(**e[0]), Chromosome.from_dict(e[1], load_gene_func))
        for e in population
    ]


def _remove_duplicates(
    population: list[tuple[Score, Chromosome]],
) -> list[tuple[Score, Chromosome]]:
    """Keep the first of each Chromosome of a population, in order."""
    clean_population, seen = [], set()
    for score, chromosome in population:
        if chromosome not in seen:
            seen.add(chromosome)
            clean_population.append((score, chromosome))
    return clean_population


def _load_metrics(
    metrics: list,
    load_decoded_chromosome_func: Callable[[Any], Any],
    load_gene_func: Callable[[Any], Any] | None,
) -> list[Metric]:
    """Load metrics of a parsed fit result file."""
    return [
        Metric.from_dict(
            m,
            load_decoded_chromosome_func=load_decoded_chromosome_func,
            load_gene_func=load_gene_func,
        )
        for m in metrics
    ]


def _load_fit_summary(
    raw: dict,
    load_decoded_chromosome_func: Callable[[Any], Any],
    load_gene_func: Callable[[Any], Any] | None,
) -> FitSummary:
    """Load a parsed fit result file, except its population and metrics."""
    bests, fit_metrics, fit_parameters = itemgetter(
        "bests", "fit_metrics", "fit_parameters"
    )(raw)
    calls = fit_metrics["fitness_func_calls"]
    # Saved as `null` when infinite. A JSON file saved before 5.0.3 by
    # this package holds `Infinity`, which loads as infinite already.
    if calls["space_points"] is None:
        fit_metrics = fit_metrics | {
            "fitness_func_calls": calls | {"space_points": inf}
        }
    response = {
        "bests": {
            "scores": [Score(**s) for s in bests["scores"]],
            "result": [
                load_decoded_chromosome_func(d) for d in bests["result"]
            ],
            "encoded": [
                Chromosome.from_dict(c, load_gene_func)
                for c in bests["encoded"]
            ],
        },
        "fit_metrics": fit_metrics,
        "fit_parameters": fit_parameters,
    }
    if config := raw.get("config"):
        response["config"] = config
    return response


def serialize_fit_result(
    fit_result: FitResult,
    serialize_decoded_chromosome_func: Callable[[Any], Any],
    serialize_gene_func: Callable[[Any], Any] | None = None,
) -> dict:
    """
    Transform the result of the function `GeneticAlgorithm.fit` into a
        serializable dictionary, i.e. a dictionary which doesn't contain
        custom classes.
    :param fit_result: what `GeneticAlgorithm.fit` returns.
    :param serialize_decoded_chromosome_func: function to get a
        serializable object from each decoded chromosome.
    :param serialize_gene_func: function to get a serializable object
        from each gene.
    :return: A dictionary with the same schema as the `fit_result`, but
        with serializable elements. It leaves out `last_population`,
        which is `history[-1]` decoded: `load_fit_result` decodes it
        again. An infinite `space_points` is `None`, as the crate saves
        it: standard JSON has no infinity.
    """
    (
        bests,
        fit_metrics,
        history,
        metrics,
        fit_parameters,
    ) = itemgetter(
        "bests",
        "fit_metrics",
        "history",
        "metrics",
        "fit_parameters",
    )(fit_result.copy())
    calls = fit_metrics["fitness_func_calls"]
    if isinf(calls["space_points"]):
        fit_metrics = fit_metrics | {
            "fitness_func_calls": calls | {"space_points": None}
        }
    bests = {
        "scores": [s.to_dict() for s in bests["scores"]],
        "result": [
            serialize_decoded_chromosome_func(d) for d in bests["result"]
        ],
        "encoded": [c.to_dict(serialize_gene_func) for c in bests["encoded"]],
    }
    history = [
        [
            (e[0].to_dict(), e[1].to_dict(serialize_gene_func))
            for e in population
        ]
        for population in history
    ]
    metrics = [
        m.to_dict(
            serialize_decoded_chromosome_func=serialize_decoded_chromosome_func,
            serialize_gene_func=serialize_gene_func,
        )
        for m in metrics
    ]
    response = {
        "bests": bests,
        "fit_metrics": fit_metrics,
        "history": history,
        "metrics": metrics,
        "fit_parameters": fit_parameters,
    }
    if config := fit_result.get("config"):
        response["config"] = config
    return response
