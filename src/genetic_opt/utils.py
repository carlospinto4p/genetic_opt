def load_fit_result(
    folder_path: str,
    load_decoded_chromosome_func: Callable[[Any], Any] | None = None,
    load_gene_func: Callable[[Any], Any] | None = None,
    remove_duplicates: bool = False,
    max_file_bytes: int | None = None,
) -> dict:
    """
    Load the content generated by `GeneticAlgorithm.fit` method.
    Args:
        folder_path: Path of the `fit_data` folder, which contains the saved
            response of the function `GeneticAlgorithm.fit`.
        load_decoded_chromosome_func: Function to load serialized Chromosomes.
            It is the identity function by default.
        load_gene_func: Function to load serialized Genes.
            It is the identity function by default.
        remove_duplicates: whether to remove duplicated chromosomes
            in each population. Default to False.
        max_file_bytes: size over which a file is refused without being
            read. No limit by default.
    Raises:
        ValidationException: a file is larger than `max_file_bytes`, or
            its content is not the one of a fit result file.
    Returns:
        dictionary with keys:
            - bests: dictionary:
                - scores: list with the 5 best Scores.
                - result: list with the 5 best chromosomes, decoded.
                - encoded: list with the 5 bests chromosomes.
            - metrics: list of metrics of each generation. Keys:
                - best: dictionary with keys:
                    - score: best Score of the population.
                    - result: best Chromosome of the population, decoded.
                    - encoded: best Chromosome of the population.
                - mean: mean of the population scores.
                - median: median of the population scores.
                - var: variance of the population scores.
                - n_uniques: number of unique Chromosomes in the population.
                - percent_uniques: percent of unique Chromosomes in the
                    population.
                - fitting_seconds: number of seconds that it took for the
                    population to get fitted.
            - fit_metrics: dict:
                - fitness_func_calls: dict:
                    - total: number of Chromosomes that needed a Score.
                    - processed: number of times the fitness function ran:
                        once for each different Chromosome.
                    - percent_processed: 100 * processed / total.
                    - cached: number of Scores taken from an earlier
                        Chromosome with the same genes.
                    - space_points: number of different Chromosomes of the
                        experiment, as a float.
                    - exploration_percentage: 100 * processed / space_points.
                - total_fit_time: dict:
                    - n_jobs: number of jobs used for processing.
                    - raw: total number of seconds of the training.
                    - formatted: same, but formatted.
            - historial: list of the tuples (Chromosome Score, Chromosome)
                for each generation.
            - fit_parameters: fit parameters used in the experiment:
                - n_generations
                - population_size
                - crossovers_prop
                - besties_prop
                - mutate_prob
                - random_seed
            - config: optional, custom dictionary added by the child classes.
    """
    files = get_files_inside_folder(folder_path, return_complete_path=True)
    load_decoded_chromosome_func = (
        load_decoded_chromosome_func or identity_func
    )
    # Every file gives its population and the metrics of its own
    # generation: the last of its `metrics`, which are all the
    # generations so far in a file saved before 0.7.0. The rest is read
    # from the file of the last generation only, kept in `last_raw`.
    generations: list[tuple[int, str, list, Metric]] = []
    last_idx, last_raw = None, None
    for file in files:
        with _refuse_malformed(file):
            raw = _read_fit_result_file(file, max_file_bytes)
            population_idx = raw["population_idx"]
            population = _load_population(
                raw["population"], load_gene_func, remove_duplicates
            )
            (metric,) = _load_metrics(
                raw["metrics"][-1:],
                load_decoded_chromosome_func,
                load_gene_func,
            )
            if last_idx is None or population_idx > last_idx:
                last_idx, last_raw = population_idx, raw
            generations.append((population_idx, file, population, metric))
    generations.sort(key=itemgetter(0))
    with _refuse_malformed(generations[-1][1]):
        response = _load_fit_summary(
            last_raw, load_decoded_chromosome_func, load_gene_func
        )
    response["metrics"] = [metric for *_, metric in generations]
    response["historial"] = [
        population for _, _, population, _ in generations
    ]
    return response


def load_fit_result_file(
    file_path: str,
    load_decoded_chromosome_func: Callable[[Any], Any] | None = None,
    load_gene_func: Callable[[Any], Any] | None = None,
    remove_duplicates: bool = False,
    max_file_bytes: int | None = None,
) -> dict:
    """
    Load the content of a single file generated by the `GeneticAlgorithm.fit`
    method.
    Args:
        file_path: Path of a BSON/JSON file.
        load_decoded_chromosome_func: Function to load serialized Chromosomes.
            It is the identity function by default.
        load_gene_func: Function to load serialized Genes.
            It is the identity function by default.
        remove_duplicates: whether to remove duplicated chromosomes
            in each population. Default to False.
        max_file_bytes: size over which the file is refused without
            being read. No limit by default.
    Raises:
        ValidationException: the file is larger than `max_file_bytes`, or
            its content is not the one of a fit result file.
    Returns:
        dictionary with keys:
            - bests: dictionary:
                - scores: list with the 5 best Scores.
                - result: list with the 5 best chromosomes, decoded.
                - encoded: list with the 5 bests chromosomes.
            - metrics: list of the metrics the file holds: those of its
                own generation, or of every generation up to its own in
                a file saved before 0.7.0. Keys:
                - best: dictionary with keys:
                    - score: best Score of the population.
                    - result: best Chromosome of the population, decoded.
                    - encoded: best Chromosome of the population.
                - mean: mean of the population scores.
                - median: median of the population scores.
                - var: variance of the population scores.
                - n_uniques: number of unique Chromosomes in the population.
                - percent_uniques: percent of unique Chromosomes in the
                    population.
                - fitting_seconds: number of seconds that it took for the
                    population to get fitted.
            - fit_metrics: dict:
                - fitness_func_calls: dict:
                    - total: number of Chromosomes that needed a Score.
                    - processed: number of times the fitness function ran:
                        once for each different Chromosome.
                    - percent_processed: 100 * processed / total.
                    - cached: number of Scores taken from an earlier
                        Chromosome with the same genes.
                    - space_points: number of different Chromosomes of the
                        experiment, as a float.
                    - exploration_percentage: 100 * processed / space_points.
                - total_fit_time: dict:
                    - n_jobs: number of jobs used for processing.
                    - raw: total number of seconds of the training.
                    - formatted: same, but formatted.
            - population: list of tuples (decoded Chromosome, Chromosome Score).
            - population_idx: population index of the experiment, starting
                with 0.
            - fit_parameters: fit parameters used in the experiment:
                - n_generations
                - population_size
                - crossovers_prop
                - besties_prop
                - mutate_prob
                - random_seed
            - config: optional, custom dictionary added by the child classes.
    """
    load_decoded_chromosome_func = (
        load_decoded_chromosome_func or identity_func
    )
    with _refuse_malformed(file_path):
        raw = _read_fit_result_file(file_path, max_file_bytes)
        response = _load_fit_summary(
            raw, load_decoded_chromosome_func, load_gene_func
        )
        response["metrics"] = _load_metrics(
            raw["metrics"], load_decoded_chromosome_func, load_gene_func
        )
        response["population"] = _load_population(
            raw["population"], load_gene_func, remove_duplicates
        )
        response["population_idx"] = raw["population_idx"]
    return response


@contextmanager
def _refuse_malformed(file_path: str) -> Iterator[None]:
    """Turn the raw errors of a malformed file into a refusal of it."""
    from bson.errors import BSONError

    try:
        yield
    except (
        AttributeError,
        BSONError,
        IndexError,
        KeyError,
        TypeError,
        ValueError,
    ) as error:
        raise ValidationException(
            f"`{file_path}` is not a fit result file: {error!r}"
        ) from error


def _read_fit_result_file(file_path: str, max_file_bytes: int | None) -> dict:
    """Parse a fit result file, refusing one over `max_file_bytes`."""
    if max_file_bytes is not None and getsize(file_path) > max_file_bytes:
        raise ValidationException(
            f"`{file_path}` has {getsize(file_path)} bytes, more than "
            f"{max_file_bytes = }"
        )
    if get_file_extension(file_path) == "bson":
        return load_bson(file_path)
    return load_json(file_path)


def _load_population(
    population: list,
    load_gene_func: Callable[[Any], Any] | None,
    remove_duplicates: bool,
) -> list[tuple[Score, Chromosome]]:
    """Load the population of a parsed fit result file."""
    population = [
        (Score(**e[0]), Chromosome.from_dict(e[1], load_gene_func))
        for e in population
    ]
    if remove_duplicates:
        clean_population, seen = [], set()
        for score, chromosome in population:
            if chromosome not in seen:
                seen.add(chromosome)
                clean_population.append((score, chromosome))
        population = clean_population
    return population


def _load_metrics(
    metrics: list,
    load_decoded_chromosome_func: Callable[[Any], Any],
    load_gene_func: Callable[[Any], Any] | None,
) -> list[Metric]:
    """Load metrics of a parsed fit result file."""
    return [
        Metric.from_dict(
            m,
            load_decoded_chromosome_func=load_decoded_chromosome_func,
            load_gene_func=load_gene_func,
        )
        for m in metrics
    ]


def _load_fit_summary(
    raw: dict,
    load_decoded_chromosome_func: Callable[[Any], Any],
    load_gene_func: Callable[[Any], Any] | None,
) -> dict:
    """Load a parsed fit result file, except its population and metrics."""
    bests, fit_metrics, fit_parameters = itemgetter(
        "bests", "fit_metrics", "fit_parameters"
    )(raw)
    response = {
        "bests": {
            "scores": [Score(**s) for s in bests["scores"]],
            "result": [
                load_decoded_chromosome_func(d) for d in bests["result"]
            ],
            "encoded": [
                Chromosome.from_dict(c, load_gene_func)
                for c in bests["encoded"]
            ],
        },
        "fit_metrics": fit_metrics,
        "fit_parameters": fit_parameters,
    }
    if config := raw.get("config"):
        response["config"] = config
    return response


def serialize_fit_result(
    fit_result: dict,
    serialize_decoded_chromosome_func: Callable[[Any], Any],
    serialize_gene_func: Callable[[Any], Any] | None = None,
) -> dict:
    """
    Transform the result of the function `GeneticAlgorithm.fit` into a
        serializable dictionary, i.e. a dictionary which doesn't contain
        custom classes.
    Args:
        fit_result: dictionary with keys:
            - bests: dictionary:
                - scores: list with the 5 best Scores.
                - result: list with the 5 best chromosomes, decoded.
                - encoded: list with the 5 bests chromosomes.
            - metrics: list of metrics of each generation. Keys:
                - best: dictionary with keys:
                    - score: best Score of the population.
                    - result: best Chromosome of the population, decoded.
                    - encoded: best Chromosome of the population.
                - mean: mean of the population scores.
                - median: median of the population scores.
                - var: variance of the population scores.
                - n_uniques: number of unique Chromosomes in the population.
                - percent_uniques: percent of unique Chromosomes in the
                    population.
                - fitting_seconds: number of seconds that it took for the
                    population to get fitted.
            - fit_metrics: dict:
                - fitness_func_calls: dict:
                    - total: number of Chromosomes that needed a Score.
                    - processed: number of times the fitness function ran:
                        once for each different Chromosome.
                    - percent_processed: 100 * processed / total.
                    - cached: number of Scores taken from an earlier
                        Chromosome with the same genes.
                    - space_points: number of different Chromosomes of the
                        experiment, as a float.
                    - exploration_percentage: 100 * processed / space_points.
                - total_fit_time: dict:
                    - n_jobs: number of jobs used for processing.
                    - raw: total number of seconds of the training.
                    - formatted: same, but formatted.
            - last_population: list of tuples
                (decoded Chromosome, Chromosome Score).
            - historial: list of the tuples (Chromosome Score, Chromosome)
                for each generation.
            - fit_parameters: fit parameters used in the experiment:
                - n_generations
                - population_size
                - crossovers_prop
                - besties_prop
                - mutate_prob
                - random_seed
            - config: optional, custom dictionary added by the child classes.
        serialize_decoded_chromosome_func: function to get a serializable
            object from each decoded chromosome.
        serialize_gene_func: function to get a serializable object from each
            gene.
    Returns:
        A dictionary with the same schema as the `fit_result`, but with
        serializable elements.
    """
    (
        bests,
        last_population,
        fit_metrics,
        historial,
        metrics,
        fit_parameters,
    ) = itemgetter(
        "bests",
        "last_population",
        "fit_metrics",
        "historial",
        "metrics",
        "fit_parameters",
    )(fit_result.copy())
    bests = {
        "scores": [s.to_dict() for s in bests["scores"]],
        "result": [
            serialize_decoded_chromosome_func(d) for d in bests["result"]
        ],
        "encoded": [c.to_dict(serialize_gene_func) for c in bests["encoded"]],
    }
    last_population = [
        (serialize_decoded_chromosome_func(d), score.to_dict())
        for d, score in last_population
    ]
    historial = [
        [
            (e[0].to_dict(), e[1].to_dict(serialize_gene_func))
            for e in population
        ]
        for population in historial
    ]
    metrics = [
        m.to_dict(
            serialize_decoded_chromosome_func=serialize_decoded_chromosome_func,
            serialize_gene_func=serialize_gene_func,
        )
        for m in metrics
    ]
    response = {
        "bests": bests,
        "last_population": last_population,
        "fit_metrics": fit_metrics,
        "historial": historial,
        "metrics": metrics,
        "fit_parameters": fit_parameters,
    }
    if config := fit_result.get("config"):
        response["config"] = config
    return response
